REQUIRED = ('title', 'date', 'slug', 'description')


def parse_note(path):
    raw = open(path, encoding='utf-8').read().replace('\r\n', '\n')
    if not raw.startswith('---\n'):
        raise SystemExit('%s: missing front matter' % os.path.basename(path))
    end = raw.find('\n---', 3)
    if end == -1:
        raise SystemExit('%s: unterminated front matter' % os.path.basename(path))

    meta = {}
    for line in raw[4:end].split('\n'):
        if not line.strip():
            continue
        if ':' not in line:
            raise SystemExit('%s: front matter line without a colon: %r' % (os.path.basename(path), line))
        key, value = line.split(':', 1)
        meta[key.strip().lower()] = value.strip().strip('"\'')

    missing = [k for k in REQUIRED if not meta.get(k)]
    if missing:
        raise SystemExit('%s: front matter missing %s' % (os.path.basename(path), ', '.join(missing)))

    try:
        date = datetime.strptime(meta['date'], '%Y-%m-%d').replace(tzinfo=timezone.utc)
    except ValueError:
        raise SystemExit('%s: date must be YYYY-MM-DD, got %r' % (os.path.basename(path), meta['date']))

    slug = meta['slug']
    if not re.match(r'^[a-z0-9][a-z0-9-]*$', slug):
        raise SystemExit('%s: slug must be lowercase letters, digits and dashes' % os.path.basename(path))

    body = raw[end + 4:].lstrip('\n')
    words = len(plain(body).split())

    return {
        'path': path,
        'title': meta['title'],
        'date': date,
        'slug': slug,
        'description': meta['description'],
        'body': body,
        'html': render_markdown(body),
        'minutes': max(1, round(words / WORDS_PER_MINUTE)),
        'url': '%s/notes/%s/' % (SITE, slug),
    }


def load_notes():
    if not os.path.isdir(CONTENT):
        raise SystemExit('no content directory at %s' % CONTENT)
    paths = sorted(p for p in os.listdir(CONTENT) if p.endswith('.md'))
    notes = [parse_note(os.path.join(CONTENT, p)) for p in paths]

    seen = {}
    for note in notes:
        if note['slug'] in seen:
            raise SystemExit('duplicate slug %r in %s and %s'
                             % (note['slug'], os.path.basename(seen[note['slug']]['path']),
                                os.path.basename(note['path'])))
        seen[note['slug']] = note

    notes.sort(key=lambda n: (n['date'], n['slug']), reverse=True)
    return notes


