#!/usr/bin/env python3
"""Build the notes section from Markdown.

    python3 build.py

Reads content/notes/*.md and writes, in the repository root:

    notes/index.html            the framed Notes app view
    notes/<slug>/index.html     one full-bleed reading page per note
    notes/feed.xml              RSS 2.0
    sitemap.xml                 every page on the site
    index.html                  the four most recent notes, injected into the
                                home screen widget between build markers

The generated HTML is committed. GitHub Pages serves index.html for a
directory, so real directories give clean URLs with no rewrite rules, no
client-side router, and no server-side anything — every article is a static
document with its own title, description and canonical URL.

Standard library only, deliberately. The site has no package.json and no
dependency tree, and a note that takes six blocks of Markdown does not justify
starting one. The Markdown support below is the subset actually used, not a
CommonMark implementation.
"""

