written = []


def write(path, text):
    # Single hook: every HTML file the build emits leaves with current asset
    # hashes, whether it was generated here or hand-written and injected into.
    if path.endswith('.html'):
        text = version_assets(text)
    existing = None
    if os.path.exists(path):
        existing = open(path, encoding='utf-8').read()
    if existing == text:
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    written.append(os.path.relpath(path, ROOT))
    return True


def prune(slugs):
    """Remove article directories for slugs that no longer exist.

    Only directories whose index.html carries this build's stamp are touched,
    so a hand-written page dropped into notes/ is never deleted by a rename.
    """
    if not os.path.isdir(NOTES_DIR):
        return
    for name in sorted(os.listdir(NOTES_DIR)):
        target = os.path.join(NOTES_DIR, name)
        if not os.path.isdir(target) or name in slugs:
            continue
        index = os.path.join(target, 'index.html')
        if os.path.isfile(index) and STAMP in open(index, encoding='utf-8').read():
            shutil.rmtree(target)
            written.append('removed ' + os.path.relpath(target, ROOT))


def main():
    notes = load_notes()
    if not notes:
        raise SystemExit('no notes found in %s' % CONTENT)

    for i, note in enumerate(notes):
        newer = notes[i - 1] if i > 0 else None
        older = notes[i + 1] if i + 1 < len(notes) else None
        write(os.path.join(NOTES_DIR, note['slug'], 'index.html'), render_article(note, newer, older))

    prune({n['slug'] for n in notes})
    write(os.path.join(NOTES_DIR, 'index.html'), render_index(notes))
    write(os.path.join(NOTES_DIR, 'feed.xml'), render_feed(notes))
    write(os.path.join(ROOT, 'sitemap.xml'), render_sitemap(notes))
    inject_widget(notes)

    print('%d note%s' % (len(notes), '' if len(notes) == 1 else 's'))
    for path in written:
        print('  ' + path)
    if not written:
        print('  everything already up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
