# ---------------------------------------------------------------------------
# Escaping
#
# Everything that comes out of a Markdown file is text until this module says
# otherwise. Both helpers below are applied to the raw source, never to markup
# the renderer has already produced.
# ---------------------------------------------------------------------------

def esc(text):
    """Escape text for an element body."""
    return html.escape(text, quote=False)


def esc_attr(text):
    """Escape text for a double-quoted attribute value."""
    return html.escape(text, quote=True)


SAFE_SCHEME = re.compile(r'^(?:https?:|mailto:|tel:)', re.I)


def safe_href(url):
    """Allow http(s), mail, tel and same-site relative links; drop the rest.

    A javascript: or data: href in a note would be a script injection with
    extra steps, and no legitimate link here needs either.
    """
    url = url.strip()
    if SAFE_SCHEME.match(url):
        return url
    if url.startswith(('/', './', '../', '#')) or re.match(r'^[\w][\w./-]*$', url):
        return url
    return '#'


# ---------------------------------------------------------------------------
# Asset versioning
#
# styles.css and the scripts keep the same URL forever, and the markup is now
# coupled to them tightly enough that a mismatch renders visibly broken rather
# than merely unstyled: a cached stylesheet that predates .note-link lays the
# widget's title and date out inline and lets the preview wrap, which inflates
# the card until it fills the screen. Appending a content hash means a changed
# stylesheet is a changed URL, so that pairing cannot happen.
# ---------------------------------------------------------------------------

def asset(name):
    """Return name with a short content hash appended, for cache busting."""
    path = os.path.join(ROOT, name)
    digest = hashlib.sha1(open(path, 'rb').read()).hexdigest()[:8]
    return '%s?v=%s' % (name, digest)


ASSET_REF = re.compile(r'(href|src)="((?:\.\./)*)(styles\.css|script\.js|clock\.js|reader\.js)(?:\?v=[0-9a-f]+)?"')


def version_assets(markup):
    """Rewrite every local asset reference to carry the current hash."""
    def sub(m):
        attr, prefix, name = m.group(1), m.group(2), m.group(3)
        return '%s="%s%s"' % (attr, prefix, asset(name))
    return ASSET_REF.sub(sub, markup)


# ---------------------------------------------------------------------------
# Markdown — inline
# ---------------------------------------------------------------------------

INLINE = re.compile(
    r'(?P<ticks>`+)(?P<code>.+?)(?P=ticks)'
    r'|!\[(?P<alt>[^\]]*)\]\((?P<src>[^)\s]+)\)'
    r'|\[(?P<text>[^\]]+)\]\((?P<href>[^)\s]+)\)'
    r'|\*\*(?P<strong>\S(?:.*?\S)?)\*\*'
    r'|(?<![\w*])\*(?P<em>[^*\n]+)\*(?![\w*])'
    r'|(?<![\w_])_(?P<em2>[^_\n]+)_(?![\w_])',
    re.S,
)


def inline(text):
    """Render bold, italic, inline code, links and images."""
    out = []
    pos = 0
    for m in INLINE.finditer(text):
        out.append(esc(text[pos:m.start()]))
        if m.group('code') is not None:
            out.append('<code>%s</code>' % esc(m.group('code')))
        elif m.group('src') is not None:
            out.append('<img src="%s" alt="%s" loading="lazy" decoding="async">'
                       % (esc_attr(safe_href(m.group('src'))), esc_attr(m.group('alt'))))
        elif m.group('href') is not None:
            href = safe_href(m.group('href'))
            ext = href.startswith(('http://', 'https://')) and not href.startswith(SITE)
            rel = ' target="_blank" rel="noopener noreferrer"' if ext else ''
            out.append('<a href="%s"%s>%s</a>' % (esc_attr(href), rel, inline(m.group('text'))))
        elif m.group('strong') is not None:
            out.append('<strong>%s</strong>' % inline(m.group('strong')))
        else:
            out.append('<em>%s</em>' % inline(m.group('em') or m.group('em2')))
        pos = m.end()
    out.append(esc(text[pos:]))
    return ''.join(out)


def plain(text):
    """Strip inline markup down to readable text, for previews and metadata."""
    text = re.sub(r'`+([^`]+)`+', r'\1', text)
    text = re.sub(r'!\[[^\]]*\]\([^)]*\)', '', text)
    text = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'\*\*(.+?)\*\*', r'\1', text, flags=re.S)
    text = re.sub(r'(?<![\w*])\*([^*\n]+)\*(?![\w*])', r'\1', text)
    text = re.sub(r'(?<![\w_])_([^_\n]+)_(?![\w_])', r'\1', text)
    return text


# ---------------------------------------------------------------------------
# Markdown — blocks
# ---------------------------------------------------------------------------

FENCE = re.compile(r'^(?P<fence>```+)\s*(?P<lang>[\w+-]*)\s*$')
HEADING = re.compile(r'^(?P<hashes>#{1,4})\s+(?P<text>.+?)\s*#*$')
BULLET = re.compile(r'^[-*]\s+(?P<text>.+)$')
ORDERED = re.compile(r'^\d+[.)]\s+(?P<text>.+)$')
RULE = re.compile(r'^(?:-{3,}|\*{3,}|_{3,})$')


def slugify(text):
    text = re.sub(r'[^\w\s-]', '', plain(text).lower()).strip()
    return re.sub(r'[\s_-]+', '-', text) or 'section'


def render_markdown(source):
    """Render the Markdown subset the notes use.

    Headings, paragraphs, bold, italic, inline code, links, images, ordered and
    unordered lists, fenced code blocks, blockquotes and horizontal rules.
    Anything else is treated as paragraph text, which is the failure mode you
    want: unsupported syntax shows up as literal characters on the page rather
    than as silently dropped content.
    """
    lines = source.replace('\r\n', '\n').split('\n')
    out = []
    seen_ids = {}
    i = 0
    n = len(lines)

    def heading_id(text):
        base = slugify(text)
        seen_ids[base] = seen_ids.get(base, 0) + 1
        return base if seen_ids[base] == 1 else '%s-%d' % (base, seen_ids[base])

    while i < n:
        line = lines[i]
        stripped = line.strip()

        if not stripped:
            i += 1
            continue

        fence = FENCE.match(stripped)
        if fence:
            marker = fence.group('fence')
            lang = fence.group('lang')
            i += 1
            body = []
            while i < n and lines[i].strip() != marker:
                body.append(lines[i])
                i += 1
            i += 1  # closing fence, or end of file
            cls = ' class="lang-%s"' % esc_attr(lang) if lang else ''
            label = ('<span class="code-lang" aria-hidden="true">%s</span>' % esc(lang)) if lang else ''
            out.append('<div class="code-block">%s<pre%s><code>%s</code></pre></div>'
                       % (label, cls, esc('\n'.join(body))))
            continue

        if RULE.match(stripped):
            out.append('<hr>')
            i += 1
            continue

        head = HEADING.match(stripped)
        if head:
            # The page supplies the h1, so body headings start at h2 — a second
            # h1 in the article would flatten the document outline. Authors
            # writing under front matter reach for "##" as their top section,
            # so "#" and "##" both land on h2 rather than "##" dropping to h3
            # and leaving the largest heading style unreachable.
            level = min(max(len(head.group('hashes')), 2), 4)
            text = head.group('text')
            out.append('<h%d id="%s">%s</h%d>'
                       % (level, esc_attr(heading_id(text)), inline(text), level))
            i += 1
            continue

        if stripped.startswith('>'):
            body = []
            while i < n and lines[i].strip().startswith('>'):
                body.append(re.sub(r'^\s*>\s?', '', lines[i]))
                i += 1
            out.append('<blockquote>%s</blockquote>' % render_markdown('\n'.join(body)))
            continue

        if BULLET.match(stripped) or ORDERED.match(stripped):
            ordered = ORDERED.match(stripped) is not None
            pattern = ORDERED if ordered else BULLET
            items = []
            while i < n:
                m = pattern.match(lines[i].strip())
                if m:
                    items.append([m.group('text')])
                    i += 1
                elif items and lines[i].strip() and not lines[i].strip().startswith(('#', '>', '```')) \
                        and lines[i][:1] in ' \t':
                    items[-1].append(lines[i].strip())  # continuation line
                    i += 1
                else:
                    break
            tag = 'ol' if ordered else 'ul'
            rendered = ''.join('<li>%s</li>' % inline(' '.join(parts)) for parts in items)
            out.append('<%s class="prose-list">%s</%s>' % (tag, rendered, tag))
            continue

        body = []
        while i < n and lines[i].strip() and not FENCE.match(lines[i].strip()) \
                and not HEADING.match(lines[i].strip()) and not lines[i].strip().startswith('>') \
                and not RULE.match(lines[i].strip()) \
                and not BULLET.match(lines[i].strip()) and not ORDERED.match(lines[i].strip()):
            body.append(lines[i].strip())
            i += 1
        out.append('<p>%s</p>' % inline(' '.join(body)))

    return '\n'.join(out)


