def long_date(d):
    return '%s %d, %d' % (d.strftime('%B'), d.day, d.year)


def short_date(d):
    """The widget's format, unchanged: month/day, no leading zeros, no year."""
    return '%d/%d' % (d.month, d.day)


def list_date(d):
    return '%d/%d/%02d' % (d.month, d.day, d.year % 100)


