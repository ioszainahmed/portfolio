RELATIVE_ATTR = re.compile(r'((?:href|src)=")(?!https?:|mailto:|tel:|#)([^"]*)"')


def absolutise(markup, base):
    """Rewrite relative hrefs against the article's own URL.

    A feed item is read somewhere else entirely, where ../another-note/ points
    at nothing. On the page itself the relative form is what keeps the site
    portable, so the rewrite happens here rather than in the renderer.
    """
    return RELATIVE_ATTR.sub(lambda m: '%s%s"' % (m.group(1), urljoin(base, m.group(2))), markup)


def render_feed(notes):
    # The newest note's date, not the wall clock. The output is committed, so a
    # build that changes nothing should produce no diff — otherwise every run
    # dirties the tree and the real change gets lost in the noise.
    built = notes[0]['date']
    items = []
    for note in notes:
        body = absolutise(note['html'], note['url']).replace(']]>', ']]&gt;')
        items.append(f'''    <item>
      <title>{esc(note['title'])}</title>
      <link>{note['url']}</link>
      <guid isPermaLink="true">{note['url']}</guid>
      <pubDate>{format_datetime(note['date'])}</pubDate>
      <description>{esc(note['description'])}</description>
      <content:encoded><![CDATA[{body}]]></content:encoded>
    </item>''')

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>{esc(FEED_TITLE)}</title>
    <link>{SITE}/notes/</link>
    <description>{esc(FEED_DESC)}</description>
    <language>en</language>
    <lastBuildDate>{format_datetime(built)}</lastBuildDate>
    <atom:link href="{SITE}/notes/feed.xml" rel="self" type="application/rss+xml" />
{chr(10).join(items)}
  </channel>
</rss>
'''


def render_sitemap(notes):
    newest = notes[0]['date'] if notes else datetime.now(timezone.utc)
    urls = [(SITE + '/', newest, '1.0'), (SITE + '/notes/', newest, '0.8')]
    urls += [(n['url'], n['date'], '0.7') for n in notes]
    body = '\n'.join(
        '  <url>\n'
        '    <loc>%s</loc>\n'
        '    <lastmod>%s</lastmod>\n'
        '    <priority>%s</priority>\n'
        '  </url>' % (loc, when.strftime('%Y-%m-%d'), priority)
        for loc, when, priority in urls
    )
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            '%s\n</urlset>\n' % body)


# ---------------------------------------------------------------------------
# Home screen widget
#
# The widget names four specific notes, so it has to stay in step with what is
# actually published. Injecting it here means adding a note is one file and one
# command, rather than one file and a hand edit somebody will forget.
# ---------------------------------------------------------------------------

def render_widget_rows(notes):
    rows = []
    for note in notes[:WIDGET_COUNT]:
        rows.append(f'''              <li class="note-item">
                <a class="note-link" href="notes/{esc_attr(note['slug'])}/">
                  <span class="note-title">{esc(note['title'])}</span>
                  <span class="note-meta">{short_date(note['date'])} &#8226; {esc(note['description'])}</span>
                </a>
              </li>''')
    return '\n'.join(rows)


def inject_widget(notes):
    path = os.path.join(ROOT, 'index.html')
    source = version_assets(open(path, encoding='utf-8').read())
    start = source.find(WIDGET_START)
    end = source.find(WIDGET_END)
    if start == -1 or end == -1:
        raise SystemExit('index.html is missing the %s / %s markers' % (WIDGET_START, WIDGET_END))

    updated = (source[:start + len(WIDGET_START)]
               + '\n' + render_widget_rows(notes) + '\n'
               + ' ' * 14 + source[end:])
    return write(path, updated)


