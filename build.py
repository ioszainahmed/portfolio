def indent(block, spaces):
    """Indent generated markup, leaving <pre> contents alone.

    Whitespace inside <pre> is content. Indenting it uniformly walked every
    line of every code sample to the right by six columns, which turned a Swift
    snippet into a staircase — visible in a render, invisible in the source.
    """
    pad = ' ' * spaces
    out = []
    depth = 0
    for line in block.split('\n'):
        out.append(pad + line if line and depth == 0 else line)
        depth += line.count('<pre') - line.count('</pre>')
    return '\n'.join(out)


def json_string(value):
    """A JSON string literal, for the ld+json blocks."""
    import json
    return json.dumps(value, ensure_ascii=False)


